export function translate(
  language: LanguageCode,
  key: TranslationKey,
  values?: Record<string, string | number>,
) {
  const template = messages[language]?.[key] ?? messages[DEFAULT_LANGUAGE][key] ?? key;
  if (!values) return template;
  return template.replace(/\{\{(\w+)\}\}/g, (_, name: string) => String(values[name] ?? ""));
}

export function translateNow(key: TranslationKey, values?: Record<string, string | number>) {
  return translate(getStoredLanguage(), key, values);
}

export function resultCount(language: LanguageCode, count: number) {
  const plural = count === 1 ? (language === "it" ? "o" : "") : language === "it" ? "i" : "s";
  return translate(language, "common.results", { count, plural });
}

export function translateDrink(language: LanguageCode, drinkType: string) {
  const key = `drink.${drinkType}` as TranslationKey;
  return key in messages[DEFAULT_LANGUAGE] ? translate(language, key) : drinkType;
}

export function translateStatus(language: LanguageCode, status: string) {
  const normalized = status.toUpperCase();
  const aliases: Record<string, TranslationKey> = {
    CONFIRMED: "status.CONFIRMADO",
    CONFIRMADO: "status.CONFIRMADO",
    PENDIENTE: "status.PENDING",
  };
  const key = aliases[normalized] ?? (`status.${normalized}` as TranslationKey);
  return key in messages[DEFAULT_LANGUAGE] ? translate(language, key) : status;
}

